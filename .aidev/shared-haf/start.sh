#!/usr/bin/env bash
# Entrypoint of the shared HAF service (.aidev/shared-haf.compose.yml), run in
# the hive/haf image of HAF_VERSION once seed.sh has seeded the version.
# Compose bind-mounts <root>/<version>/haf_db_store directly at
# /home/hived/datadir/haf_db_store — the path the image's postgresql.conf and
# tablespace were written for. This script checks that mount holds a cluster,
# adds the clone setting and memory sizing and hands over to the HAF entrypoint, which starts
# PostgreSQL and then runs serve.sh.
#
# Environment: HAF_VERSION, HAF_SHARED_ROOT (as seed.sh; read by serve.sh).
set -euo pipefail

root="${HAF_SHARED_ROOT:?HAF_SHARED_ROOT must name the mounted ZFS dataset}"
here="$(cd "$(dirname "$0")" && pwd -P)"
store=/home/hived/datadir/haf_db_store

# Only the device tells the dataset's copy apart from the image's own
# directory at $store.
if [ -L "$store" ] || [ "$(stat -c %d "$store")" != "$(stat -c %d "$root")" ] \
    || ! sudo -n test -f "$store/pgdata/PG_VERSION"; then
    echo "$store is not the seeded cluster bind-mounted from the data root" >&2
    exit 1
fi

conf_d=/home/hived/datadir/haf_postgresql_conf.d
sudo -n mkdir -p "$conf_d"
sudo -n install -o postgres -g postgres -m 644 "$here/postgresql.conf" "$conf_d/50-haf-shared.conf"

# PostgreSQL's memory, sized from the container's limit (the host's memory
# when it has none), but never from more than sizing_bound_mb: shared memory is
# charged to the cgroup and cannot be reclaimed, so shared_buffers takes a
# quarter, leaving the rest to the backends of concurrent consumers. AIDEV
# changes the limit of a running container, and shared memory cannot shrink
# without a restart, so the sizing must also fit the smallest limit the
# container may be lowered to in place: the dev-stack's 5.5 GB. See
# .aidev/README.md.
sizing_bound_mb=5632
limit_mb=$(cat /sys/fs/cgroup/memory.max 2>/dev/null || echo max)
if [[ "$limit_mb" =~ ^[0-9]+$ ]]; then
    limit_mb=$((limit_mb / 1024 / 1024))
else
    limit_mb=$(($(awk '/^MemTotal:/ { print $2 }' /proc/meminfo) / 1024))
fi
sizing_mb=$((limit_mb < sizing_bound_mb ? limit_mb : sizing_bound_mb))
at_least() { local v=$(($1)); ((v < $2)) && v=$2; echo "$v"; }
shared_buffers_mb=$(at_least "sizing_mb / 4" 256)
maintenance_work_mem_mb=$(at_least "sizing_mb / 16" 64)
sudo -n tee "$conf_d/60-haf-shared-memory.conf" > /dev/null <<EOF
# Generated by start.sh for a memory limit of ${limit_mb}MB, sized for ${sizing_mb}MB.
shared_buffers = ${shared_buffers_mb}MB
effective_cache_size = $(at_least "sizing_mb / 2" 512)MB
work_mem = $(at_least "sizing_mb / 128" 4)MB
maintenance_work_mem = ${maintenance_work_mem_mb}MB
autovacuum_work_mem = $(at_least "maintenance_work_mem_mb / 4" 16)MB
EOF
sudo -n chown postgres:postgres "$conf_d/60-haf-shared-memory.conf"
echo "Memory limit ${limit_mb}MB, sized for ${sizing_mb}MB: shared_buffers = ${shared_buffers_mb}MB" >&2

exec /home/hived/docker_entrypoint.sh --execute-maintenance-script="$here/serve.sh"
